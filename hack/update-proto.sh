#!/usr/bin/env bash

# Vendors loadbalancer/v1/loadbalancer.proto from the LoadBalancer API repo and
# regenerates the Go bindings under pkg/rpc/loadbalancer/gen.
#
# Requires buf, protoc-gen-go and protoc-gen-go-grpc on PATH. buf resolves the
# buf.build/bufbuild/protovalidate dependency from its module cache, so this
# works offline once that module has been fetched at least once.
#
# Usage:
#   hack/update-proto.sh [path/to/loadbalancer.proto]

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UPSTREAM_PROTO="${1:-${REPO_ROOT}/../loadbalancer-api/proto/loadbalancer/v1/loadbalancer.proto}"

# The descriptor path is baked into the generated code and into the global proto
# registry key, so the proto has to sit at this exact path inside the buf module.
PROTO_PATH="pkg/rpc/loadbalancer/gen/loadbalancer.proto"
GO_PACKAGE="kubevirt.io/cloud-provider-kubevirt/pkg/rpc/loadbalancer/gen"

for tool in buf protoc-gen-go protoc-gen-go-grpc; do
	command -v "$tool" >/dev/null || { echo "$tool not found on PATH" >&2; exit 1; }
done
[ -f "$UPSTREAM_PROTO" ] || { echo "upstream proto not found: $UPSTREAM_PROTO" >&2; exit 1; }

cp "$UPSTREAM_PROTO" "${REPO_ROOT}/${PROTO_PATH}"

# buf is run in a throwaway workspace rather than against the repo so that no
# buf.yaml/buf.lock has to live in the tree.
WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

mkdir -p "$(dirname "${WORK_DIR}/${PROTO_PATH}")"
cp "${REPO_ROOT}/${PROTO_PATH}" "${WORK_DIR}/${PROTO_PATH}"

cat >"${WORK_DIR}/buf.yaml" <<'EOF'
version: v2
modules:
  - path: .
deps:
  - buf.build/bufbuild/protovalidate
EOF

# The lock pins the protovalidate module so buf resolves it from its local cache
# instead of reaching for the BSR. Prefer the upstream repo's own lock; the
# embedded copy is the fallback for when only the .proto is available.
UPSTREAM_LOCK="$(cd "$(dirname "$UPSTREAM_PROTO")/../../.." 2>/dev/null && pwd)/buf.lock"
if [ -f "$UPSTREAM_LOCK" ]; then
	cp "$UPSTREAM_LOCK" "${WORK_DIR}/buf.lock"
else
	cat >"${WORK_DIR}/buf.lock" <<'EOF'
# Generated by buf. DO NOT EDIT.
version: v2
deps:
  - name: buf.build/bufbuild/protovalidate
    commit: 50325440f8f24053b047484a6bf60b76
    digest: b5:74cb6f5c0853c3c10aafc701614194bbd63326bdb8ef4068214454b8894b03ba4113e04b3a33a8321cdf05336e37db4dc14a5e2495db8462566914f36086ba31
EOF
fi

cat >"${WORK_DIR}/buf.gen.yaml" <<EOF
version: v2
plugins:
  - local: protoc-gen-go
    out: .
    opt:
      - module=kubevirt.io/cloud-provider-kubevirt
      - M${PROTO_PATH}=${GO_PACKAGE}
  - local: protoc-gen-go-grpc
    out: .
    opt:
      - module=kubevirt.io/cloud-provider-kubevirt
      - M${PROTO_PATH}=${GO_PACKAGE}
EOF

(cd "$WORK_DIR" && buf generate)

# Drop the blank import of the protovalidate Go bindings. The buf.validate
# options are documentation on this side - nothing here reads them at runtime,
# they survive in the raw descriptor either way, and keeping the import would
# add a module dependency purely so an unused extension registers itself.
sed -i '/buf\.build\/gen\/go\/bufbuild\/protovalidate/d' \
	"${WORK_DIR}/pkg/rpc/loadbalancer/gen/loadbalancer.pb.go"

cp "${WORK_DIR}/pkg/rpc/loadbalancer/gen/loadbalancer.pb.go" \
	"${WORK_DIR}/pkg/rpc/loadbalancer/gen/loadbalancer_grpc.pb.go" \
	"${REPO_ROOT}/pkg/rpc/loadbalancer/gen/"

gofmt -w "${REPO_ROOT}/pkg/rpc/loadbalancer/gen/loadbalancer.pb.go"

echo "regenerated ${GO_PACKAGE} from ${UPSTREAM_PROTO}"
